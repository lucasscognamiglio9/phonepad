#!/usr/bin/env bash
# User installation. Converges every machine to the same state: the repo's
# binary, units and modules, with no drop-ins or leftovers from older releases.
# Keeps pairing and service.env. Run setup.sh with sudo once before this.
# Usage: PHONEPAD_PREBUILT=/path/phonepad bash setup/install.sh
set -euo pipefail
script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
repo_dir=$(cd -- "$script_dir/.." && pwd)
config_dir=${XDG_CONFIG_HOME:-$HOME/.config}/phonepad
unit_dir=${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user
bin_dir=$HOME/.local/bin
lib_dir=$HOME/.local/lib/phonepad
ext_dst=$HOME/.local/share/gnome-shell/extensions/phonepad@local
[[ $# == 0 ]] || { echo 'Uso: install.sh' >&2; exit 1; }

[[ -w /dev/uinput ]] || { echo 'No puedo escribir /dev/uinput. Corré: sudo bash setup/setup.sh y volvé a entrar a la sesión.' >&2; exit 1; }
for tool in wl-copy wl-paste; do
 command -v "$tool" >/dev/null || { echo "Falta $tool. Corré: sudo bash setup/setup.sh" >&2; exit 1; }
done
/usr/bin/python3 -c "import gi; gi.require_version('GstWebRTC', '1.0'); gi.require_version('AyatanaAppIndicator3', '0.1')" 2>/dev/null \
 || { echo 'Faltan GStreamer WebRTC o el indicador. Corré: sudo bash setup/setup.sh' >&2; exit 1; }

mkdir -p "$config_dir" "$unit_dir" "$bin_dir" "$ext_dst"
if [[ -n ${PHONEPAD_PREBUILT:-} ]]; then
 install -m 755 "$PHONEPAD_PREBUILT" "$bin_dir/phonepad.new"
else
 go_bin=$(command -v go || true)
 [[ -n $go_bin ]] || { echo 'Falta Go o PHONEPAD_PREBUILT.' >&2; exit 1; }
 (cd "$repo_dir/daemon"; "$go_bin" build -trimpath -mod=vendor -o "$bin_dir/phonepad.new" .)
fi
mv "$bin_dir/phonepad.new" "$bin_dir/phonepad"

# Older releases redirected ExecStart to temporary directories through
# drop-ins; when those directories were deleted the services broke.
for unit in phonepad-health.timer phonepad-health.service; do
 systemctl --user disable --now "$unit" 2>/dev/null || true
done
rm -rf "$unit_dir"/phonepad*.service.d
rm -f "$unit_dir"/phonepad*.previous "$unit_dir"/phonepad-health.{service,timer} \
 "$bin_dir"/phonepad.pre-* "$config_dir"/video.env "$config_dir"/hfr.env

rm -rf "$lib_dir"
mkdir -p "$lib_dir"
install -m 644 "$script_dir/preview/"*.py "$lib_dir/"
install -m 755 "$script_dir/indicator.py" "$lib_dir/indicator.py"
for unit in phonepad.service phonepad-preview.service phonepad-indicator.service; do
 install -m 644 "$script_dir/$unit" "$unit_dir/$unit"
done
install -m 644 "$script_dir/gnome-extension/phonepad@local/extension.js" "$ext_dst/extension.js"
install -m 644 "$script_dir/gnome-extension/phonepad@local/metadata.json" "$ext_dst/metadata.json"

# Existing configuration and identity are never regenerated by installation.
if [[ ! -f "$config_dir/service.env" ]]; then
 umask 077
 printf 'PHONEPAD_BIND=127.0.0.1\nPHONEPAD_HOST=localhost\n' > "$config_dir/service.env"
fi

# The native pointer layer needs the GNOME session variables inside systemd.
if [[ -n ${WAYLAND_DISPLAY:-} ]]; then
 systemctl --user import-environment WAYLAND_DISPLAY DISPLAY XDG_RUNTIME_DIR XDG_CURRENT_DESKTOP XDG_SESSION_TYPE XAUTHORITY
else
 echo 'Aviso: corré este script desde la sesión gráfica de GNOME para que el puntero use la capa nativa.' >&2
fi

# The indicator is the only panel widget; the extension would duplicate it.
gnome-extensions disable phonepad@local 2>/dev/null || true
systemctl --user daemon-reload
for unit in phonepad.service phonepad-preview.service phonepad-indicator.service; do
 systemctl --user enable "$unit"
 systemctl --user restart "$unit"
done

sleep 2
for unit in phonepad.service phonepad-preview.service phonepad-indicator.service; do
 printf '%s: %s\n' "$unit" "$(systemctl --user is-active "$unit" || true)"
done
pointer=$(journalctl --user -u phonepad.service --since -10s -o cat | grep -m1 'PhonePad pointer' || true)
echo "${pointer:-PhonePad pointer: sin registro todavía}"
case $pointer in
 *'linear native motion'*) ;;
 *) echo 'Aviso: el puntero no usa la capa nativa de GNOME; se comporta como el touchpad de la máquina.' >&2 ;;
esac
printf 'Emparejar una vez: https://localhost:8080/pair\nCompartir pantalla: https://localhost:8080/share\n'
